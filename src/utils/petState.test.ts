import assert from 'node:assert/strict';
import { nextPet, petTaskChanges, petTierForStreak, type PetState, type PetContext } from './petState';
const context: PetContext = { pendingCount: 2, vibrateOk: true };
const states: PetState[] = ['idle', 'roaming', 'happy', 'curious', 'thinking', 'sad', 'sleeping', 'welcome-back', 'overwhelmed', 'celebration-streak', 'coffee-break'];
for (const state of states) {
  const completion = nextPet(state, 'feed-task-done', context);
  assert.equal(completion.state, state === 'celebration-streak' ? 'celebration-streak' : 'happy');
  assert.equal(nextPet(state, 'env-transient-end', context).state, 'idle');
}
assert.equal(nextPet('idle', 'feed-major-task-done', context).state, 'celebration-streak');
assert.equal(nextPet('idle', 'feed-streak-milestone', context).state, 'celebration-streak');
assert.equal(nextPet('idle', 'feed-task-added', context).state, 'curious');
assert.equal(nextPet('idle', 'feed-task-added', { ...context, pendingCount: 10 }).state, 'overwhelmed');
assert.equal(nextPet('idle', 'env-variation', { ...context, variation: 'roam' }).state, 'roaming');
assert.equal(nextPet('idle', 'env-variation', { ...context, vibrateOk: false, variation: 'roam' }).state, 'idle');
assert.equal(nextPet('idle', 'env-variation', { ...context, variation: 'coffee' }).state, 'coffee-break');
assert.equal(nextPet('roaming', 'env-variation', { ...context, variation: 'think' }).state, 'roaming');
assert.equal(nextPet('idle', 'env-inactivity-slump', context).state, 'sad');
assert.equal(nextPet('idle', 'env-doze', context).state, 'sleeping');
assert.equal(nextPet('sleeping', 'env-coffee-break', context).state, 'sleeping');
assert.equal(nextPet('sleeping', 'feed-user-wake', context).state, 'welcome-back');
assert.equal(nextPet('sad', 'feed-user-wake', context).state, 'idle');
assert.equal(nextPet('idle', 'feed-user-wake', context).state, 'idle');
assert.equal(petTierForStreak(undefined), 'normal');
assert.equal(petTierForStreak(3), 'active');
assert.equal(petTierForStreak(7), 'streak-master');
const before = [{ id: 'a', isDone: false }, { id: 'b', isDone: false }, { id: 'done', isDone: true }];
assert.equal(petTaskChanges(before, before).completed, 0);
assert.equal(petTaskChanges(before, []).completed, 0, 'Deleting tasks or reflection cleanup must not trigger spins');
assert.equal(petTaskChanges(before, before.map(t => ({ ...t, isDone: true }))).completed, 2, 'Batched completions each get a spin');
assert.equal(petTaskChanges([], [{ id: 'new', isDone: true }]).completed, 0, 'Loading completed records is not a new completion');
assert.equal(petTaskChanges(before, [{ id: 'done', isDone: false }]).completed, 0, 'Undoing completion does not celebrate');
assert.equal(petTaskChanges(before, [...before, { id: 'new', isDone: false }]).added, true);
console.log('Pet behavior, completion detection, batching, deletion and undo regression tests passed.');