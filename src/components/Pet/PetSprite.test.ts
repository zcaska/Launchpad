import assert from 'node:assert/strict';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { PetSprite, resolveMascotVisual, getPetMotionClass } from './PetSprite';
import { MASCOT_EXPRESSIONS, MASCOT_STATE_POSES } from './mascotManifest';
const props = { state: 'idle' as const, tier: 'normal' as const, facing: 1 as const, isFlying: false, isDragging: false, isSippingCoffee: false, reducedMotion: true, petted: false };
const idle = renderToStaticMarkup(createElement(PetSprite, props));
assert(!idle.includes('data-prop="laptop"'));
assert(!Object.keys(MASCOT_EXPRESSIONS).includes('focused'));
assert(!Object.keys(MASCOT_EXPRESSIONS).includes('determined'));
assert(!Object.keys(MASCOT_STATE_POSES).includes('focus'));
assert.equal(resolveMascotVisual('happy', false, false).expression, 'excited');
assert.equal(resolveMascotVisual('thinking', false, false).expression, 'curious');
assert.equal(resolveMascotVisual('welcome-back', false, false).expression, 'welcoming');
assert.equal(resolveMascotVisual('coffee-break', false, false).expression, 'calm');
assert.equal(resolveMascotVisual('idle', true, false).expression, 'happy');
assert.equal(resolveMascotVisual('idle', false, true).expression, 'surprised');
const excited = renderToStaticMarkup(createElement(PetSprite, { ...props, state: 'happy', evolutionLevel: 7 }));
assert.match(excited, /data-expression="excited"/);
assert.match(excited, /data-testid="pet-completion-spin"/);
assert.match(excited, /data-accessory="jeweled-crown"/);
assert.equal(getPetMotionClass('happy', true, false, false), '');
assert.equal(getPetMotionClass('happy', false, true, false), '');
const coffee = renderToStaticMarkup(createElement(PetSprite, { ...props, state: 'coffee-break', isSippingCoffee: true }));
assert.match(coffee, /pet-steam/);
console.log('Rendered excited pet, removed focus presets, accessories and pause behavior tests passed.');